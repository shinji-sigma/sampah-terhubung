async (page) => {
  await page.getByRole('button',{name:'Buka navigasi',exact:true}).click()
  await page.keyboard.press('Escape')
  const menu = page.getByRole('button',{name:'Buka navigasi',exact:true})
  if (!(await menu.evaluate(e=>e===document.activeElement))) throw Error('Escape did not restore menu focus')
  await menu.click()
  await page.getByRole('button',{name:'Jadwal angkut',exact:true}).click()
  const input = page.getByLabel('Mulai tanggal')
  const iso = await input.inputValue()
  if(!/^\d{4}-\d{2}-\d{2}$/.test(iso)) throw Error('Date input no longer ISO')
  const source = page.getByText('Sumber & ketentuan layanan',{exact:true})
  await source.focus()
  await page.keyboard.press('Enter')
  if (!(await source.locator('..').getAttribute('open')) && (await source.locator('..').getAttribute('open'))!== '') throw Error('Keyboard details did not open')
  await page.getByText('Masa berlaku',{exact:true}).waitFor()
  await page.screenshot({path:'output/playwright/design-revision/after/mobile-schedule-details.png',fullPage:true})
  await menu.click()
  await page.getByRole('button',{name:'Beranda',exact:true}).click()
  const incident = page.locator('.incident-detail > summary').first()
  await incident.focus()
  await page.keyboard.press('Enter')
  await page.getByText('40000000-0000-4000-8000-000000000001',{exact:true}).waitFor()
  const smallButtons = await page.evaluate(()=>[...document.querySelectorAll('button')].filter(e=>!e.disabled&&e.getBoundingClientRect().width>0&&e.getBoundingClientRect().height<44).map(e=>e.textContent))
  const metadataMinimum = await page.evaluate(()=>Math.min(...[...document.querySelectorAll('.small-muted,.badge,.schedule-source')].filter(e=>e.getBoundingClientRect().width>0).map(e=>parseFloat(getComputedStyle(e).fontSize))))
  if(smallButtons.length || metadataMinimum<14) throw Error(JSON.stringify({smallButtons,metadataMinimum}))
  return {menuEscapeFocus:true,keyboardSourceDetails:true,keyboardIncidentFullId:true,inputISO:iso,metadataMinimum,smallButtons}
}
